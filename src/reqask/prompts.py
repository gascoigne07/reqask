def _already_found(findings: list[Finding], empty: str = "Первый проход замечаний не нашёл.") -> str:
    if not findings:
        return empty
    rows = []
    for f in findings:
        where = ", ".join(f.req_ids) if f.req_ids else "набор"
        rows.append(f"- {f.criterion} | {where} | {' '.join((f.title or f.problem).split())[:200]}")
    return "\n".join(rows)


