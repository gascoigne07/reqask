def segmentation_prompt(numbered_text: str, outline: str, part: tuple[int, int] | None) -> str:
    scope = ""
    if part:
        scope = (
            f"\nДокумент большой, сейчас перед тобой его часть: строки {part[0]}-{part[1]}. "
            "Оглавление всего документа дано для ориентира.\n"
        )
    outline_block = f"\nОглавление документа:\n{outline}\n" if outline and part else ""
    return f"""Задача: разметить в документе границы отдельных требований номерами строк.
{scope}
Что считать требованием: утверждение, которое задаёт обязательное поведение, свойство, ограничение, \
данные, интерфейс или условие приёмки для системы или процесса. Сюда входят функциональные \
и нефункциональные требования, бизнес-правила, требования к данным, интеграции и интерфейсу, \
параметры и коды ответов API, шаги алгоритма, критерии приёмки, описания экранов, схем и примеров, \
если из них следует обязательное поведение. Строка таблицы, которая задаёт правило, параметр, поле, \
код ответа или сценарий приёмки, считается требованием.

Что не считать требованием, а перечислить в skipped с причиной:
- heading: заголовки и оглавление;
- service: служебные поля и сведения о документе (автор, версия, владелец, ссылки на трекер, \
согласующие, подписи);
- history: история изменений;
- checklist: чек-листы ревью и согласования;
- template: пустые шаблоны, заглушки, строки шапок таблиц, незаполненные поля;
- intro: вводный и поясняющий текст без обязательства, а также констатация, которая ничего не требует \
от системы: строка только сообщает, что чего-то нет, что-то отсутствует или не применяется, и не задаёт \
ни запрета, ни условия, ни значения. Явный запрет («не должен», «запрещено», «не допускается») это требование;
- other: прочее, что не требование.
Проверка для спорной строки: если по ней нельзя написать тест, который система может провалить, это не требование.
Эти строки всё равно проверит другой шаг, здесь они нужны, чтобы ни одна строка не потерялась.

Правила нарезки:
- Если у требования в документе есть свой идентификатор (например «FR-1», «ФТ-3», «REQ-12», номер пункта), \
сохрани единицу как в документе и запиши идентификатор в source_id. Составное требование не дроби \
на части фразы, даже если внутри несколько утверждений.
- Без идентификатора: одно требование это один пункт списка, одна строка таблицы или один абзац \
с одним обязательством. Если независимые обязательства стоят на разных строках, раздели их по строкам.
- Блок кода или пример (JSON, curl, схема), который задаёт формат или поведение, включи в требование, \
к которому он относится. Если он единственный источник правила, выдели его отдельно.
- line_start и line_end: номера первой и последней строки по разметке слева (L0012 означает 12). \
Диапазоны требований не пересекаются. Текст требования не пересказывай, нужны только номера строк.
- section: заголовок ближайшего раздела.
- kind: одно из значений: {KINDS_HELP}.
- summary: суть требования своими словами, до 15 слов, без оценки качества.

Пройди документ от первой строки до последней. Каждая строка с текстом должна попасть либо \
в requirements, либо в skipped.
{outline_block}
Документ (слева номера строк):
{numbered_text}"""


def _req_block(req: Requirement) -> str:
    head = f"[{req.id}] ID в документе: {req.source_id or 'нет'}; раздел: {req.section or 'не указан'}; " \
           f"строки {req.line_start}-{req.line_end}"
    hints = ""
    if req.lint_hints:
        hints = "\nПодсказки линтера (кандидаты, решение за тобой): " + "; ".join(req.lint_hints)
    return f"{head}\n<<<\n{req.quote}\n>>>{hints}"


def review_prompt(batch: list[Requirement], context: str, context_is_full: bool) -> str:
    context_title = (
        "Документ целиком, для контекста (слева номера строк)"
        if context_is_full
        else "Фрагмент документа вокруг этих требований, для контекста (слева номера строк)"
    )
    blocks = "\n\n".join(_req_block(r) for r in batch)
    return f"""Задача: проверить каждое требование из списка по девяти критериям качества отдельного требования.

Критерии (код, название, источник, что проверять):
{describe(REQ_CRITERIA)}

Уровни критичности:
{SEVERITY_RULES}

Как проверять:
- Проверяй каждое требование по всем девяти критериям по очереди. Найденный дефект не завершает проверку: \
остальные критерии смотри так же внимательно. У одного требования бывает несколько дефектов по разным критериям, \
каждый нарушенный критерий записывай отдельным дефектом.
- Смотри на требование в контексте документа. Термин или значение могут быть определены в другом разделе, \
тогда это не дефект.
- Проверяй и текст, и технические детали: типы и форматы данных, диапазоны и границы, единицы измерения, \
методы и коды ответов протокола, соответствие примера описанию.
- Требование, которое противоречит само себе или своему примеру, это дефект CONSISTENT этого требования. \
Противоречия между разными требованиями здесь не ищи, их сравнивает отдельный шаг.
- Подсказка линтера это кандидат. Решай по контексту: слово может быть уместным.
- Замечание по NECESSARY и CORRECT формулируй как вопрос к автору, а не как утверждение: \
агент не знает потребность заказчика лучше него.
- За стиль и оформление не ставь CRITICAL. Оформление по шаблону здесь не проверяй.
- Требование без дефектов это нормальный результат, если все девять критериев проверены и ни один не нарушен. \
Тогда все оценки pass, а defects пустые.

checks: ровно девять оценок, по одной на каждый критерий, в порядке списка выше. Пропускать критерий нельзя.
- pass: критерий выполнен, note пустая строка;
- fail: критерий нарушен, по нему есть дефект в defects;
- na: критерий к требованию не применим (например, осуществимость для пояснения к примеру);
- unknown: по тексту оценить нельзя, нужен ответ автора.
note для fail, na и unknown: до 20 слов, почему так.
Сначала поставь оценку по каждому критерию, потом опиши дефекты: на каждый fail свой дефект с тем же criterion.

Для каждого дефекта заполни:
- criterion: код критерия. Один дефект относится к одному критерию, два нарушенных критерия дают два дефекта.
- severity: уровень по правилам выше.
- evidence: дословная цитата из текста этого требования, минимальный фрагмент от трёх слов, где виден дефект. \
Для пропуска цитируй фрагмент, рядом с которым не хватает сведений. line: номер строки цитаты.
- problem: что не так, 1-2 предложения с опорой на цитату.
- impact: что из-за этого нельзя сделать (реализовать, проверить, оценить срок), одно предложение.
- recommendation: что уточнить или как переписать.

{QUESTION_RULES}

rewritten: если у требования есть дефекты CRITICAL или MAJOR, дай готовую исправленную формулировку. \
Значение, которого нет в документе, не выдумывай: на его месте ставь метку в угловых скобках, \
например <N секунд> или <роль пользователя>. Если таких дефектов нет, null.

Верни reviews для всех требований списка, в том же порядке, с теми же req_id.

Требования для проверки:

{blocks}

{context_title}:
{context}"""


def _req_table(requirements: list[Requirement]) -> str:
    rows = []
    for r in requirements:
        rows.append(f"{r.id} | {r.source_id or '-'} | строки {r.line_start}-{r.line_end} | {r.summary}")
    return "\n".join(rows)


def _criteria_with_sections(criteria) -> str:
    return "\n".join(
        f"- {c.code} ({c.name}; {c.source}; подраздел «{SET_SECTIONS[c.group]}»): {c.question}" for c in criteria
    )


