def _already_found(findings: list[Finding]) -> str:
    if not findings:
        return "Первый проход замечаний не нашёл."
    rows = []
    for f in findings:
        where = ", ".join(f.req_ids) if f.req_ids else "набор"
        rows.append(f"- {f.criterion} | {where} | {' '.join((f.title or f.problem).split())[:200]}")
    return "\n".join(rows)


