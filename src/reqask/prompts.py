def _finding_row(f: Finding) -> str:
    where = ", ".join(f.req_ids) if f.req_ids else (f"раздел «{f.section}»" if f.section else "набор в целом")
    text = " ".join((f.title or f.problem).split())[:300]
    quote = next((e for e in f.evidence if e.status != "missing"), None)
    quote = f" | строка {quote.line}: «{' '.join(quote.quote.split())[:120]}»" if quote else ""
    if f.question:
        question = f" | вопрос ({f.addressee}): {' '.join(f.question.split())}"
    else:
        question = " | вопроса нет" if f.severity != "MINOR" else ""
    return f"{f.id} | {f.severity} | {f.criterion} | {f.kind} | {where} | {text}{quote}{question}"


